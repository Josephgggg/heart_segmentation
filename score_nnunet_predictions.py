"""Score nnU-Net's validation predictions with this repo's metrics.

This is the bridge that makes the nnU-Net arm comparable to everything else.
nnU-Net runs as its own pipeline in its own venv and writes predictions as
NIfTI; this script -- run in unet_env -- turns them into the same
`*_metrics_per_patient.csv` schema every other arm produces, so
`metrics.compare_runs` can pair the two arms on (patient_id, class_name) and run
the paired Wilcoxon.

Nothing here re-implements a metric. `metrics.rows_for_volume` is already
model-free (it takes two label volumes and a spacing), so the only new code is
assembling the ground-truth volume and aligning the prediction to it. Same loop
shape as rescore_annotated_extent.py, whose `metrics.predict_volume(net, ...)`
call is the one thing replaced.

Predictions come back in the geometry they were exported in -- (Z, Y, X) in this
repo's canonical orientation, because export_nnunet_dataset.py deliberately
exported in that orientation rather than the source NIfTI's. So no inverse
transform is needed, only a possible resample; see --grid.

--grid is REQUIRED and has no default, because the choice materially changes the
comparison and should be made deliberately:

  matched  Score on the 216x216 grid the control was trained and scored on
           (img_scale=0.5, in-plane spacing 1.3935 mm). nnU-Net's predictions
           are downsampled to it with INTER_NEAREST. Pairs directly against the
           CSVs that already exist, but discards the fine detail nnU-Net
           produced, handicapping it at scoring time.

  native   Score at 432x432 with true spacing (0.6968 mm). Does not handicap
           nnU-Net, but the control's existing CSVs are NOT on this grid -- they
           must be regenerated by upsampling the control's 216x216 predictions
           before the two can be paired. This script does not do that; it only
           scores nnU-Net.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import cv2
import nibabel as nib
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from train import BOTH_CLASS_NAMES                      # noqa: E402
from utils import metrics                               # noqa: E402
from utils.data_loading import VolumeMRIDataset         # noqa: E402

PHASE = 'both'
N_CLASSES = 6
SCALE_FOR_GRID = {'matched': 0.5, 'native': 1.0}


def gt_volume(ds, pid):
    """Ground-truth label volume for one patient, straight out of the dataset.

    Assembled by stacking `ds[i]['mask']` in ascending slice order rather than
    re-reading the NIfTI, so the GT is preprocessed by exactly the code path
    that scored every other arm -- same reorientation, same nearest-neighbour
    resize, same mask_values mapping. Re-deriving it independently would be the
    easiest possible way to introduce a silent off-by-one or a flipped axis.
    """
    idx = [i for i, (p, _) in enumerate(ds.index) if p == pid]
    if not idx:
        raise SystemExit(f'{pid}: not present in dataset.index')
    idx.sort(key=lambda i: ds.index[i][1])
    return np.stack([np.asarray(ds[i]['mask']) for i in idx]).astype(np.uint8)


def load_prediction(path, target_shape):
    """nnU-Net prediction, resampled to the scoring grid if needed."""
    pred = np.asanyarray(nib.load(path).dataobj).astype(np.uint8)
    if pred.shape[0] != target_shape[0]:
        raise SystemExit(f'{path.name}: {pred.shape[0]} slices, GT has {target_shape[0]}')
    if pred.shape[1:] != target_shape[1:]:
        h, w = target_shape[1:]
        pred = np.stack([cv2.resize(sl, (w, h), interpolation=cv2.INTER_NEAREST)
                         for sl in pred])
    return pred


def self_check(ds, pids, cache_dir, scale):
    """Validate the GT assembly against the raw cache, before trusting anything.

    Checks orientation, slice ordering and the resize in one shot, and needs no
    predictions and no GPU -- so it can run before a single fold is trained.
    """
    print(f'self-check: GT assembly vs {cache_dir} at scale={scale}')
    ok = True
    for pid in pids:
        gt = gt_volume(ds, pid)
        raw = np.load(cache_dir / f'{pid}_{PHASE}_mask.npy').astype(np.uint8)
        if scale == 1.0:
            expect = raw
        else:
            h = w = int(raw.shape[1] * scale)
            expect = np.stack([cv2.resize(sl, (w, h), interpolation=cv2.INTER_NEAREST)
                               for sl in raw])
        same = gt.shape == expect.shape and np.array_equal(gt, expect)
        ok &= same
        print(f'  {pid:22s} gt={gt.shape} labels={np.unique(gt)} '
              f'{"MATCH" if same else "MISMATCH"}')
    print('self-check', 'PASS' if ok else 'FAIL')
    return ok


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--grid', choices=sorted(SCALE_FOR_GRID), required=True,
                    help='scoring grid; see module docstring. No default on purpose.')
    ap.add_argument('--results', type=Path,
                    default=Path('/hpc/jgeo610/nnunet/results/Dataset501_CardiacBoth/'
                                 'nnUNetTrainer_250epochs__nnUNetPlans__3d_fullres'))
    ap.add_argument('--splits', type=Path,
                    default=Path('/hpc/jgeo610/nnunet/preprocessed/Dataset501_CardiacBoth/'
                                 'splits_final.json'))
    ap.add_argument('--imgs', type=Path, default=Path('data/imgs'))
    ap.add_argument('--masks', type=Path, default=Path('data/masks'))
    ap.add_argument('--cache-dir', type=Path, default=Path('data/preprocessed_cache'))
    ap.add_argument('--out', type=Path, default=Path('checkpoints/nnunet_3d_fullres_pooled'))
    ap.add_argument('--self-check', action='store_true',
                    help='only validate GT assembly against the cache, then exit')
    ap.add_argument('--control-runs',
                    default='checkpoints/both_data_aug_dice_ce_kfold{fold}',
                    help="control run dir template containing '{fold}'; its five "
                         'per-fold CSVs are pooled and compared against')
    ap.add_argument('--no-compare', action='store_true',
                    help='write the CSVs but skip the paired comparison')
    args = ap.parse_args()

    scale = SCALE_FOR_GRID[args.grid]
    ds = VolumeMRIDataset(args.imgs, args.masks, scale=scale, phase=PHASE)
    splits = json.loads(args.splits.read_text())

    if args.self_check:
        pids = sorted(splits[0]['val'])[:3]
        sys.exit(0 if self_check(ds, pids, args.cache_dir, scale) else 1)

    rows = []
    for fold, split in enumerate(splits):
        val_dir = args.results / f'fold_{fold}' / 'validation'
        if not val_dir.is_dir():
            raise SystemExit(f'{val_dir} missing -- has fold {fold} finished training?')
        for pid in sorted(split['val']):
            pred_path = val_dir / f'{pid}.nii.gz'
            if not pred_path.is_file():
                raise SystemExit(f'{pred_path} missing')
            gt = gt_volume(ds, pid)
            pred = load_prediction(pred_path, gt.shape)
            rows += metrics.rows_for_volume(
                pred, gt, pid, N_CLASSES,
                spacing=ds.spacing_for(pid),
                class_names=BOTH_CLASS_NAMES, compute_hd95=True,
                extra={'fold': fold})
            print(f'  fold {fold}  {pid:22s} {gt.shape}', flush=True)

    n_patients = len({r['patient_id'] for r in rows})
    if n_patients != 42:
        raise SystemExit(f'expected 42 pooled validation patients, scored {n_patients}')

    args.out.mkdir(parents=True, exist_ok=True)
    metrics.write_csv(rows, args.out / 'val_metrics_per_patient.csv')
    summary = metrics.summarise(rows)
    metrics.write_csv(summary, args.out / 'val_metrics_summary.csv')
    (args.out / 'run_config.json').write_text(json.dumps({
        'run_name': f'nnunet_3d_fullres_{args.grid}',
        'arch': 'nnunet_3d_fullres', 'trainer': 'nnUNetTrainer_250epochs',
        'framework': 'nnunetv2', 'scoring_grid': args.grid, 'img_scale': scale,
        'phase': PHASE, 'n_classes': N_CLASSES, 'split_seed': 0, 'k_folds': len(splits),
        'finished': True,
    }, indent=2))

    print(f'\nwrote {args.out}/val_metrics_{{per_patient,summary}}.csv  '
          f'({n_patients} patients, grid={args.grid})')
    print(metrics.format_summary(summary))

    if args.no_compare:
        return

    # Pool the control's five per-fold CSVs. The folds hold disjoint patients, so
    # pooling is plain concatenation -- the same thing the kfold diagnostics
    # notebooks do, and what makes a 42-patient paired test possible instead of
    # five 8-or-9-patient ones.
    pooled = []
    for fold in range(len(splits)):
        csv_path = Path(args.control_runs.format(fold=fold)) / 'val_metrics_per_patient.csv'
        if not csv_path.is_file():
            raise SystemExit(f'{csv_path} missing -- cannot pool the control arm')
        pooled += metrics.load_per_patient(csv_path)
    ctrl_patients = {r['patient_id'] for r in pooled}
    if ctrl_patients != {r['patient_id'] for r in rows}:
        raise SystemExit('control and nnU-Net patient sets differ -- refusing to compare')

    ctrl_csv = args.out / 'control_pooled_per_patient.csv'
    metrics.write_csv(pooled, ctrl_csv)
    print(f'\npooled control: {len(ctrl_patients)} patients -> {ctrl_csv}')

    cmp = metrics.compare_runs(ctrl_csv, args.out / 'val_metrics_per_patient.csv',
                               label_a='unet_2d', label_b=f'nnunet_3d_{args.grid}')
    print(metrics.format_comparison(cmp, 'unet_2d', f'nnunet_3d_{args.grid}'))
    print('\nNOTE: 3d_fullres vs a 2D control -- part of any difference is 3D-vs-2D,\n'
          '      not nnU-Net-vs-UNet. See CLAUDE.md.')


if __name__ == '__main__':
    main()
